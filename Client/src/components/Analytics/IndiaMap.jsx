export default function IndiaMap({
  stateData = [],
  selectedState = null,
  onSelectState = () => {},
}) {
  const [hoveredState, setHoveredState] = useState(null);
  const [tooltipPos, setTooltipPos] = useState({ x: 0, y: 0 });

  // Map stateData array into lookup map
  const statsByState = React.useMemo(() => {
    const map = new Map();
    (stateData || []).forEach((item) => {
      if (item && item.state) {
        map.set(item.state.toLowerCase(), item);
      }
    });
    return map;
  }, [stateData]);

  // Max orders in any state for dynamic color scaling
  const maxOrders = React.useMemo(() => {
    let max = 0;
    (stateData || []).forEach((item) => {
      if (item.orders > max) max = item.orders;
    });
    return max > 0 ? max : 1;
  }, [stateData]);

  // Smooth choropleth gradient
  const getStateColor = (stateName) => {
    const data = statsByState.get(stateName.toLowerCase());
    const count = data?.orders || 0;

    if (count === 0) return "#f8fafc"; // Slate-50

    const ratio = count / maxOrders;

    if (ratio > 0.75) return "#0284c7"; // Sky-600
    if (ratio > 0.45) return "#38bdf8"; // Sky-400
    if (ratio > 0.2) return "#7dd3fc"; // Sky-300
    return "#bae6fd"; // Sky-200
  };

  const handleMouseMove = (e, state) => {
    const rect = e.currentTarget.closest("svg").getBoundingClientRect();
    setTooltipPos({
      x: e.clientX - rect.left,
      y: e.clientY - rect.top,
    });
    const info = statsByState.get(state.name.toLowerCase()) || {
      state: state.name,
      orders: 0,
      share: 0,
      delivered: 0,
      rto: 0,
      freight: 0,
      successRate: 0,
    };
    setHoveredState(info);
  };

  const handleMouseLeave = () => {
    setHoveredState(null);
  };

  return (
    <div className="relative w-full flex flex-col items-center select-none">
      {/* MAP SVG CONTAINER WITH SUBTLE AMBIENT GLOW */}
      <div className="relative w-full max-w-[500px] aspect-[612/696] rounded-2xl p-2 bg-gradient-to-b from-sky-50/40 via-white to-slate-50/60 border border-slate-100 shadow-inner">
        <svg
          viewBox="0 0 612 696"
          className="w-full h-full filter drop-shadow-sm transition-all"
        >
          {/* DEFINITIONS FOR FILTERS & GLOW */}
          <defs>
            <filter id="mapGlow" x="-20%" y="-20%" width="140%" height="140%">
              <feDropShadow dx="0" dy="2" stdDeviation="3" floodColor="#0284c7" floodOpacity="0.25" />
            </filter>
            <radialGradient id="oceanGlow" cx="50%" cy="50%" r="60%">
              <stop offset="0%" stopColor="#f0f9ff" stopOpacity="0.8" />
              <stop offset="100%" stopColor="#ffffff" stopOpacity="0" />
            </radialGradient>
          </defs>

          {/* WATERMARK BACKGROUND GLOW */}
          <ellipse cx="300" cy="380" rx="260" ry="300" fill="url(#oceanGlow)" />

          {/* ALL STATE PATHS */}
          <g id="india-states-layer">
            {INDIA_STATE_PATHS.map((st) => {
              const fillColor = getStateColor(st.name);
              const isSelected =
                selectedState &&
                selectedState.toLowerCase() === st.name.toLowerCase();
              const isHovered =
                hoveredState &&
                hoveredState.state.toLowerCase() === st.name.toLowerCase();

              return (
                <path
                  key={st.id}
                  id={`state-${st.id}`}
                  d={st.d}
                  fill={isSelected ? "#008dd2" : fillColor}
                  stroke={isSelected ? "#003b5c" : isHovered ? "#0284c7" : "#cbd5e1"}
                  strokeWidth={isSelected ? 2.8 : isHovered ? 2.2 : 1.2}
                  strokeLinejoin="round"
                  strokeLinecap="round"
                  filter={isSelected || isHovered ? "url(#mapGlow)" : undefined}
                  className="cursor-pointer transition-all duration-200 ease-out hover:opacity-95"
                  onMouseMove={(e) => handleMouseMove(e, st)}
                  onMouseLeave={handleMouseLeave}
                  onClick={() =>
                    onSelectState(selectedState === st.name ? null : st.name)
                  }
                />
              );
            })}
          </g>

          {/* STATE CODE LABELS AT TRUE CENTROIDS */}
          <g id="state-labels" pointerEvents="none">
            {INDIA_STATE_PATHS.map((st) => {
              const data = statsByState.get(st.name.toLowerCase());
              const count = data?.orders || 0;
              const isSelected =
                selectedState &&
                selectedState.toLowerCase() === st.name.toLowerCase();

              return (
                <text
                  key={`label-${st.id}`}
                  x={st.cx}
                  y={st.cy}
                  textAnchor="middle"
                  alignmentBaseline="central"
                  className={`text-[10px] font-extrabold tracking-tight transition-colors duration-150 ${
                    isSelected
                      ? "fill-white font-black"
                      : count > 0
                      ? "fill-slate-900"
                      : "fill-slate-400"
                  }`}
                >
                  {st.id}
                </text>
              );
            })}
          </g>
        </svg>

        {/* FLOATING GLASSMORPHIC TOOLTIP */}
        {hoveredState && (
          <div
            className="pointer-events-none absolute z-30 transform -translate-x-1/2 -translate-y-full mb-3 w-52 rounded-xl border border-sky-100 bg-white/95 p-3.5 shadow-2xl backdrop-blur-md transition-all duration-150 animate-in fade-in"
            style={{
              left: `${Math.min(Math.max(tooltipPos.x, 105), 395)}px`,
              top: `${Math.max(tooltipPos.y - 12, 10)}px`,
            }}
          >
            <div className="flex items-center justify-between border-b border-slate-100 pb-2 mb-2">
              <span className="font-bold text-[13px] text-slate-900 truncate">
                {hoveredState.state}
              </span>
              <span className="rounded bg-sky-100 text-[#008dd2] px-1.5 py-0.5 text-[10px] font-bold">
                {hoveredState.share || 0}% Share
              </span>
            </div>

            <div className="space-y-1.5 text-[11px]">
              <div className="flex items-center justify-between text-slate-600">
                <span>Total Orders:</span>
                <span className="font-extrabold text-slate-900 text-[12px]">
                  {hoveredState.orders || 0}
                </span>
              </div>
              <div className="flex items-center justify-between text-slate-600">
                <span>Delivered:</span>
                <span className="font-bold text-emerald-600">
                  {hoveredState.delivered || 0} ({hoveredState.successRate || 0}%)
                </span>
              </div>
              <div className="flex items-center justify-between text-slate-600">
                <span>RTO Returned:</span>
                <span className="font-bold text-rose-600">
                  {hoveredState.rto || 0}
                </span>
              </div>
              <div className="flex items-center justify-between text-slate-600 pt-1.5 border-t border-slate-100">
                <span>Total Freight:</span>
                <span className="font-bold text-slate-900">
                  ₹{Number(hoveredState.freight || 0).toLocaleString("en-IN")}
                </span>
              </div>
            </div>
          </div>
        )}
      </div>

      {/* HEATMAP COLOR SCALE LEGEND */}
      <div className="mt-3.5 flex items-center justify-center gap-2 text-[11px] font-medium text-slate-500">
        <span className="text-[10px] uppercase font-bold text-slate-400">
          Order Density:
        </span>
        <div className="flex items-center gap-2">
          <span className="flex items-center gap-1">
            <span className="h-3 w-3 rounded-xs border border-slate-200 bg-[#f8fafc]" />
            <span className="text-[10px]">0</span>
          </span>
          <span className="flex items-center gap-1">
            <span className="h-3 w-3 rounded-xs bg-[#bae6fd]" />
            <span className="text-[10px]">Low</span>
          </span>
          <span className="flex items-center gap-1">
            <span className="h-3 w-3 rounded-xs bg-[#7dd3fc]" />
            <span className="text-[10px]">Mid</span>
          </span>
          <span className="flex items-center gap-1">
            <span className="h-3 w-3 rounded-xs bg-[#38bdf8]" />
            <span className="text-[10px]">High</span>
          </span>
          <span className="flex items-center gap-1">
            <span className="h-3 w-3 rounded-xs bg-[#0284c7]" />
            <span className="text-[10px]">Top</span>
          </span>
        </div>
      </div>
    </div>
  );
}
